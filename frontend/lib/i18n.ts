export function getSavedLang(): Lang {
  try {
    const saved = localStorage.getItem(LANG_STORAGE);
    if (saved === "zh" || saved === "en") return saved;
  } catch {}
  return "en";
}

export function saveLang(lang: Lang) {
  try {
    localStorage.setItem(LANG_STORAGE, lang);
  } catch {}
}
